/* Real HTTP/SQLite/worker + Chromium; only inference is synthetic. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const BASE = process.env.GROUPING_BASE;
const ROOT = process.env.LOCALSCRIBE_GROUPING_TEST_ROOT;
(async () => {
  const {jobId} = JSON.parse(await fs.readFile(ROOT+'/fixture.json','utf8'));
  const browser = await chromium.launch({headless:true, executablePath:process.env.BROWSER_EXECUTABLE});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage(); const errors=[]; const external=[]; const checks=[];
  page.on('pageerror', error=>errors.push(error.message));
  await context.route('**/*', route=>{ if(route.request().url().startsWith(BASE+'/')) return route.continue(); external.push(route.request().url());return route.abort(); });
  const record = text=>{checks.push(text);console.log('PASS '+text);};
  const path = '/api/jobs/'+jobId;
  const read = async suffix=>(await (await page.request.get(BASE+path+suffix)).json());
  const post = async (suffix, body)=> { const {token}=await (await page.request.get(BASE+'/api/session')).json();return page.request.post(BASE+path+suffix,{data:body,headers:{'X-LocalScribe-Token':token}}); };
  const waitRevision = revision=>page.waitForFunction(revision=>document.querySelector('.save-state')?.textContent.includes('revision '+revision),revision);
  const tools = page.getByRole('region',{name:'AI proofreading',exact:true});
  try {
    await page.goto(BASE+'/#job='+jobId);
    await tools.getByText('Loaded model: synthetic-browser',{exact:true}).waitFor();
    await tools.getByLabel('Proofreading scope',{exact:true}).selectOption('block');
    await tools.getByLabel('Proofreading block',{exact:true}).selectOption('399');
    await page.getByRole('button',{name:'Preview grouping',exact:true}).click();
    await page.getByRole('button',{name:'Apply all',exact:true}).click();await waitRevision(1);
    assert.equal(await tools.getByLabel('Proofreading block',{exact:true}).inputValue(),'0');
    await tools.getByLabel('Proofreading glossary',{exact:true}).fill('LocalScribe, Marcin');
    await tools.getByRole('button',{name:'Preview AI corrections',exact:true}).click();
    await tools.getByText(/suggestions\. Pending suggestions/).waitFor({timeout:15000});
    assert.equal((await read('/transcript')).revision,1);
    assert.deepEqual((await read('/proofreading')).glossary,['LocalScribe','Marcin']);
    assert.ok(await tools.locator('del').count());assert.ok(await tools.locator('ins').count());
    record('grouping -> saved-block proofreading -> bounded inline diff; pending corrections excluded from saved revision');
    await tools.getByRole('button',{name:'Reject suggestion',exact:true}).first().click();
    await tools.getByRole('button',{name:'Select all corrections',exact:true}).click();
    await tools.getByRole('button',{name:'Accept selected corrections',exact:true}).click();await waitRevision(2);
    const accepted = await read('/transcript');
    assert.ok(accepted.segments.some(s=>s.editedText?.endsWith('!')));
    assert.equal((await read('/history')).operations.at(-1).type,'proofreading');
    record('individual rejection and selected acceptance save one reversible batch with unchanged source IDs and timing');
    await page.getByRole('button',{name:'Undo saved operation',exact:true}).click();await waitRevision(3);
    assert.ok((await read('/transcript')).segments.every(s=>s.editedText===null));
    await page.getByRole('button',{name:'Redo saved operation',exact:true}).click();await waitRevision(4);
    assert.deepEqual((await read('/transcript')).segments,accepted.segments);
    record('Undo/Redo restores exact accepted values without another inference request');
    await tools.getByLabel('Proofreading scope',{exact:true}).selectOption('entire');
    await tools.getByRole('button',{name:'Preview AI corrections',exact:true}).click();
    await tools.getByRole('button',{name:'Cancel proofreading',exact:true}).click();
    await tools.getByText('Proofreading cancelled.',{exact:true}).waitFor({timeout:10000});
    assert.equal((await read('/transcript')).revision,4);
    record('whole-recording cancellation drains the current chunk and publishes no late corrections');
    await fs.writeFile(ROOT+'/mode.txt','malformed');
    await tools.getByRole('button',{name:'Preview AI corrections',exact:true}).click();
    await tools.getByText('Proofreading failed.',{exact:true}).waitFor({timeout:10000});
    assert.equal((await read('/transcript')).revision,4);
    await fs.writeFile(ROOT+'/mode.txt','normal');
    record('malformed/unknown-ID inference output fails safely and keeps saved exports unchanged');
    await tools.getByLabel('Proofreading scope',{exact:true}).selectOption('block');
    await tools.getByLabel('Proofreading block',{exact:true}).selectOption('1');
    await tools.getByRole('button',{name:'Preview AI corrections',exact:true}).click();
    await tools.getByText(/suggestions\. Pending suggestions/).waitFor({timeout:15000});
    const details=page.locator('.block-sources').first();if(!(await details.evaluate(el=>el.open)))await details.locator('summary').click();
    const draft=page.locator('[data-segment="s000"] textarea');await draft.fill('Visible draft.');
    assert.ok(await tools.getByRole('button',{name:'Preview AI corrections',exact:true}).isDisabled());
    await tools.getByRole('button',{name:'Select all corrections',exact:true}).isDisabled().then(assert.ok);
    const {token}=await (await page.request.get(BASE+'/api/session')).json();
    await page.request.patch(BASE+path+'/transcript',{data:{revision:4,texts:{s002:'Saved elsewhere.'},names:{}},headers:{'X-LocalScribe-Token':token}});
    await tools.getByRole('button',{name:'Refresh model & suggestions',exact:true}).click();
    await tools.getByText('Suggestions are stale. Start a new preview for the saved revision.',{exact:true}).waitFor();
    assert.equal(await draft.inputValue(),'Visible draft.');
    record('manual drafts gate AI actions; stale results preserve a visible draft after another-tab save');
    page.once('dialog', dialog=>dialog.accept());
    await page.getByRole('button',{name:'Discard changes',exact:true}).click();await waitRevision(5);
    for(const width of [1440,760,390]) {await page.setViewportSize({width,height:1000});const open=page.locator('.transcript-tools');if(await open.count()){}assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);}
    record('desktop and narrow layouts keep cleanup controls without horizontal overflow');
    assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
    await fs.writeFile(ROOT+'/proofreading-state.json',JSON.stringify({revision:5,segments:(await read('/transcript')).segments}));
    await fs.writeFile(ROOT+'/proofreading-results.json',JSON.stringify({checks,pageErrors:errors,externalRequests:external},null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
